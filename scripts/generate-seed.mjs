// Writes supabase/seed.sql from the old catalogue in public/app.js plus the confirmed store settings.
// Run: npm run db:seed:generate. The output is safe to run more than once.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadLegacyCatalog } from './lib/legacy-catalog.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const { categories, products, warnings, legacyCount } = loadLegacyCatalog(`${root}public/app.js`);

const q = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);
const rows = (list) => list.map((r) => `  (${r.join(', ')})`).join(',\n');

// Business rules confirmed by the owner on 2026-10-16. Change them later in the admin panel.
const settings = {
  whatsapp_number: '919942089120',
  delivery_tiers: [
    { min: 0, fee: 50 },
    { min: 200, fee: 30 },
    { min: 500, fee: 20 },
    { min: 800, fee: 0 },
  ],
  store_hours: {
    mon: { open: '09:00', close: '21:00' },
    tue: { open: '09:00', close: '21:00' },
    wed: { open: '09:00', close: '21:00' },
    thu: { open: '09:00', close: '21:00' },
    fri: { open: '09:00', close: '21:00' },
    sat: { open: '09:00', close: '21:00' },
    sun: { open: '10:00', close: '18:00' },
  },
  contact_phone: '+91 99420 89120',
  alternate_phone: '+91 78570 33161',
  contact_email: 'orderkarokishanganj@gmail.com',
  google_review_url: 'https://g.page/r/Caa1t0LPjd8YEBM/review',
};

const variants = products.flatMap((p) => p.variants.map((v) => ({ ...v, product_slug: p.slug })));
const images = products.flatMap((p) => p.images.map((img) => ({ ...img, product: p })));

const sql = `-- Generated by scripts/generate-seed.mjs from public/app.js. Do not edit by hand.
-- ${legacyCount} old catalogue items -> ${products.length} products with ${variants.length} sizes in ${categories.length} categories.
-- Safe to run more than once: existing rows are left alone.

insert into public.settings (id, whatsapp_number, delivery_tiers, min_order_value, store_hours, store_open,
  contact_phone, alternate_phone, contact_email, google_review_url)
values (true, ${q(settings.whatsapp_number)}, ${q(JSON.stringify(settings.delivery_tiers))}::jsonb, 0,
  ${q(JSON.stringify(settings.store_hours))}::jsonb, true,
  ${q(settings.contact_phone)}, ${q(settings.alternate_phone)}, ${q(settings.contact_email)}, ${q(settings.google_review_url)})
on conflict (id) do nothing;

insert into public.categories (slug, name_en, name_hi, sort_order)
values
${rows(categories.map((c) => [q(c.slug), q(c.name_en), q(c.name_hi), c.sort_order]))}
on conflict (slug) do nothing;

insert into public.products (slug, category_id, name_en, name_hi, featured, sort_order)
select v.slug, c.id, v.name_en, v.name_hi, v.featured, v.sort_order
from (values
${rows(products.map((p) => [q(p.slug), q(p.category_slug), q(p.name_en), q(p.name_hi), p.featured, p.sort_order]))}
) as v (slug, category_slug, name_en, name_hi, featured, sort_order)
join public.categories c on c.slug = v.category_slug
on conflict (slug) do nothing;

insert into public.product_variants (product_id, legacy_id, unit_en, unit_hi, price, mrp, sort_order)
select p.id, v.legacy_id, v.unit_en, v.unit_hi, v.price, v.mrp, v.sort_order
from (values
${rows(variants.map((v) => [q(v.product_slug), q(v.legacy_id), q(v.unit_en), q(v.unit_hi), v.price, v.mrp, v.sort_order]))}
) as v (product_slug, legacy_id, unit_en, unit_hi, price, mrp, sort_order)
join public.products p on p.slug = v.product_slug
on conflict (legacy_id) do nothing;

insert into public.product_images (product_id, storage_path, alt_en, alt_hi, is_primary, sort_order)
select p.id, v.storage_path, v.alt_en, v.alt_hi, v.is_primary, v.sort_order
from (values
${rows(images.map((img) => [q(img.product.slug), q(img.storage_path), q(img.product.name_en), q(img.product.name_hi), img.is_primary, img.sort_order]))}
) as v (product_slug, storage_path, alt_en, alt_hi, is_primary, sort_order)
join public.products p on p.slug = v.product_slug
where not exists (
  select 1 from public.product_images i where i.product_id = p.id and i.storage_path = v.storage_path
);
`;

writeFileSync(`${root}supabase/seed.sql`, sql);
console.log(`supabase/seed.sql: ${products.length} products, ${variants.length} sizes, ${images.length} images, ${categories.length} categories.`);
for (const w of warnings) console.log(`note: ${w}`);
